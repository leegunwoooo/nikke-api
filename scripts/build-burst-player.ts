import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const result = await build({ absWorkingDir: root, entryPoints: ["viewer/player.ts"], bundle: true,
  format: "iife", platform: "browser", target: "es2022", minify: true, legalComments: "inline", write: false });
const license = await readFile(path.join(root, "viewer/SPINE-LICENSE.txt"), "utf8");
const code = `/*\n${license.replaceAll("\r\n", "\n")}\n*/\n${result.outputFiles[0].text}`;
const output = `// Generated by npm run build:burst-player.\nexport const BURST_PLAYER = ${JSON.stringify(code)};\n`;
const file = path.join(root, "src/burst-player.generated.ts");
if (process.argv.includes("--check")) {
  if ((await readFile(file, "utf8")).replaceAll("\r\n", "\n") !== output) throw new Error("Run npm run build:burst-player and commit the generated player.");
} else await writeFile(file, output);
