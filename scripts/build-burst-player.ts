import { build } from "esbuild";
import { readFile, rename, writeFile } from "node:fs/promises";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const result = await build({ absWorkingDir: root, entryPoints: ["viewer/player.ts"], bundle: true,
  format: "iife", platform: "browser", target: "es2022", minify: true, legalComments: "inline", write: false });
const license = await readFile(path.join(root, "viewer/SPINE-LICENSE.txt"), "utf8");
const code = `/*\n${license.replaceAll("\r\n", "\n")}\n*/\n${result.outputFiles[0].text}`;
const output = `// Generated by npm run build:burst-player.\nexport const BURST_PLAYER = ${JSON.stringify(code)};\n`;
const file = path.join(root, "src/burst-player.generated.ts");
const current = await readFile(file, "utf8").then((s) => s.replaceAll("\r\n", "\n"), () => null);
if (process.argv.includes("--check")) {
  if (current !== output) throw new Error("Run npm run build:burst-player and commit the generated player.");
} else if (current !== output) {
  // test files run in parallel and import this module — a plain writeFile
  // leaves a truncated window readers can hit mid-run. Write only on a real
  // change, and via temp+rename so readers see either the old or new file
  const tmp = `${file}.tmp`;
  await writeFile(tmp, output);
  await rename(tmp, file);
}
